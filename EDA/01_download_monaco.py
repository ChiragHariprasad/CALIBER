"""
Download the raw OpenF1 data used by the CALIBRE Monaco EDA.

Run:
    python 01_download_monaco.py

By default this downloads the endpoints needed to reproduce the EDA and
also saves telemetry/location for the race session. Set DOWNLOAD_HEAVY=True
if you want all five Monaco sessions for car_data/location.
"""

import json
from pathlib import Path

import requests

from EDA.figures.config import (
    API_BASE,
    MEETING_KEY,
    RACE_SESSION_KEY,
    REPORTED_SESSION_KEYS,
    RAW_DIR,
)

DOWNLOAD_HEAVY = False  # True = car_data + location for all 5 sessions
REQUEST_TIMEOUT = 120


def get_json(endpoint, params=None):
    url = f"{API_BASE}/{endpoint}"
    r = requests.get(url, params=params or {}, timeout=REQUEST_TIMEOUT)
    r.raise_for_status()
    return r.json()


def save_json(name, payload):
    path = RAW_DIR / f"{name}.json"
    with path.open("w", encoding="utf-8") as f:
        json.dump(payload, f)
    print(f"[saved] {path} ({len(payload):,} rows)")


def download_endpoint(endpoint, session_key):
    payload = get_json(endpoint, {"session_key": session_key})
    save_json(f"{endpoint}_session_{session_key}", payload)
    return payload


def main():
    print("Discovering Monaco sessions...")
    sessions = get_json("sessions", {"meeting_key": MEETING_KEY})
    save_json("monaco_sessions", sessions)

    session_keys = sorted(
        {int(s["session_key"]) for s in sessions}
    )
    print("Discovered sessions:", session_keys)

    # Core EDA endpoints across the full Monaco weekend.
    for sk in session_keys:
        for endpoint in ["laps", "pit", "stints", "race_control"]:
            download_endpoint(endpoint, sk)

    # Supporting datasets for the race session.
    for endpoint in ["car_data", "location", "intervals", "position", "weather", "drivers", "session_result"]:
        try:
            download_endpoint(endpoint, RACE_SESSION_KEY)
        except requests.HTTPError as exc:
            print(f"[warning] {endpoint}: {exc}")

    # Timing-system raw topic is not available from OpenF1; CALIBRE
    # reconstructs loop crossings with its timing-system twin.
    print("\nOpenF1 does not provide raw OTS loop crossings.")
    print("Those records must be generated by CALIBRE's timing-system twin.")

    if DOWNLOAD_HEAVY:
        print("\nDownloading car_data + location for all Monaco sessions...")
        for sk in session_keys:
            for endpoint in ["car_data", "location"]:
                download_endpoint(endpoint, sk)

    print("\nDownload complete.")
    print("Raw files are in:", RAW_DIR)


if __name__ == "__main__":
    main()
